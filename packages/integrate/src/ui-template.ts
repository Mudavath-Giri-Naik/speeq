/** Voice modes the generated widget can be configured for. */
export type VoiceMode = "none" | "browser" | "cloud" | "sarvam";

/** Options for {@link renderAssistant}. All values are escaped; nothing is executed. */
export interface AssistantOptions {
  voice: VoiceMode;
  /** BCP 47 tags, the first is the default. */
  languages: readonly string[];
  /** Show a "Mock mode" badge (no real model is connected). */
  mock: boolean;
  /** Display name, shown in the header and used for the accessible label. */
  name?: string;
  /** Things the visitor can tap to start (for example `Open Pricing`). Shown with the greeting. */
  suggestions?: readonly string[];
}

const LANGUAGE_NAMES: Record<string, string> = {
  "en-IN": "English",
  "en-US": "English (US)",
  "te-IN": "తెలుగు",
  "hi-IN": "हिन्दी",
};

