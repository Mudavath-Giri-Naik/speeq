/** Only paths on this site: a relative path that cannot become another site. */
function safePath(href: string) {
  return href.startsWith("/") && !href.startsWith("//") && !href.includes(String.fromCharCode(92));
}
function greetingFor(hour: number) {
  const hello = hour < 5 ? "Hey" : hour < 12 ? "Good morning" : hour < 17 ? "Good afternoon" : hour < 22 ? "Good evening" : "Hey";
  return hello + "! I'm " + NAME + ". I can take you to any page here and help you get things done. What are you after?";
}

