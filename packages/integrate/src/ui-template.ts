/** Source of `components/speeq/assistant.tsx` (without the ownership header). */
export function renderAssistant(o: AssistantOptions): string {
  const names: Record<string, string> = {};
  for (const tag of o.languages) names[tag] = LANGUAGE_NAMES[tag] ?? tag;
  const imports = [
    imp("{ SpeeqProvider, useSpeeq }", "speeq/react"),
    imp("{ useRouter }", "next/navigation"),
    imp("{ type FormEvent, useEffect, useId, useLayoutEffect, useRef, useState }", "react"),
  ].join("\n");
  const fill: Record<string, string> = {
    __IMPORTS__: imports,
    __NAME__: JSON.stringify((o.name ?? "Assistant").slice(0, 40)),
    __LANGUAGES__: JSON.stringify([...o.languages]),
    __LANGUAGE_NAMES__: JSON.stringify(names),
    __MOCK__: o.mock ? "true" : "false",
    __SUGGESTIONS__: JSON.stringify(
      [...(o.suggestions ?? [])].slice(0, 4).map((s) => s.slice(0, 40)),
    ),
    __VOICE__: JSON.stringify(o.voice),
  };
  return TEMPLATE.replace(/__[A-Z_]+__/g, (key) => fill[key] ?? key);
}
