import { posix } from "node:path";
import type { FeatureEntry, ProviderEntry } from "./registry.js";

/** How a generated tool reaches host code. */
export type ToolCall =
  | { kind: "function"; file: string; exportName: string }
  | { kind: "endpoint"; method: string; path: string; query: string[]; forwardAuth: boolean };
/** One approved tool, ready to render. All text is data; rendering quotes it. */
export interface ToolSpec {
  name: string;
  description: string;
  summary: string;
  write: boolean;
  /** Explicit `confirm: false` from the decision. */
  noConfirm: boolean;
  /** Zod source for the input object. */
  input: string;
  auth?: { roles?: string[] };
  timeoutMs?: number;
  call: ToolCall;
}
/** One approved route, ready to render. */
export interface RouteSpec {
  id: string;
  path: string;
  title: string;
  description?: string;
  /** Zod source for params, when the route has any. */
  params?: string;
}
const q = (s: string) => JSON.stringify(s);
/** Relative module specifier without extension, e.g. `../../src/lib/cart`. */
export function importPath(from: string, to: string): string {
  const rel = posix
    .relative(posix.dirname(from), to)
    .replace(/\.(?:tsx?|jsx?|mjs|mts|cjs|cts)$/, "");
  return rel.startsWith("../") ? rel : `./${rel}`;
}
const NOTE =
  "// Generated by speeq. Do not edit: delete the first line to take ownership of this file.";

/** Source of `.speeq/generated/tools.ts` (without the ownership header). */
export function renderTools(tools: readonly ToolSpec[], file: string): string {
  const imports = new Set<string>(["defineTool"]);
  const hosts: string[] = [];
  const decls: string[] = [];
  const needsGuard = tools.some((t) => t.auth);
  if (needsGuard) imports.add("SpeeqError");
  const hasEndpoint = tools.some((t) => t.call.kind === "endpoint");
  if (hasEndpoint) imports.add("bindEndpoint");
  const items = tools.map((t, i) => {
    const n = i + 1;
    let run: string;
    if (t.call.kind === "function") {
      const alias = `host${n}`;
      const spec = t.call.exportName === "default" ? alias : `{ ${t.call.exportName} as ${alias} }`;
      hosts.push(`import ${spec} from ${q(importPath(file, t.call.file))};`);
      run = `${alias}(input as Parameters<typeof ${alias}>[0])`;
    } else {
      const c = t.call;
      const timeout = t.timeoutMs ? `, timeoutMs: ${t.timeoutMs}` : "";
      decls.push(
        `const call${n} = bindEndpoint({ baseUrl, method: ${q(c.method)}, path: ${q(c.path)}, query: ${JSON.stringify(c.query)}, forwardAuth: ${c.forwardAuth}${timeout} });`,
      );
      run = `call${n}(input as Record<string, unknown>, ctx)`;
    }
    const roles = t.auth?.roles ? `, ${JSON.stringify(t.auth.roles)}` : "";
    const guard = t.auth ? `guard(ctx${roles}); ` : "";
    return [
      "  defineTool({",
      `    name: ${q(t.name)},`,
      `    description: ${q(t.description)},`,
      `    input: ${t.input},`,
      ...(t.write ? ['    risk: "write",'] : []),
      ...(t.noConfirm ? ["    requiresConfirmation: false,"] : []),
      ...(t.write ? [`    confirmationSummary: () => ${q(t.summary)},`] : []),
      ...(t.timeoutMs && t.call.kind === "function" ? [`    timeoutMs: ${t.timeoutMs},`] : []),
      `    handler: async (input, ctx) => { ${guard}return ${run}; },`,
      "  }),",
    ].join("\n");
  });
  if (tools.length === 0) imports.clear();
  const head = [NOTE];
  if (tools.length === 0) head.push('import type { ToolDefinition } from "speeq/server";');
  else head.push(`import { ${[...imports].sort().join(", ")} } from "speeq/server";`);
  if (tools.length) head.push('import { z } from "zod";');
  head.push(...hosts, "");
  if (hasEndpoint)
    head.push(
      'const baseUrl = process.env.SPEEQ_BASE_URL ?? "http://localhost:3000";',
      "",
      ...decls,
      "",
    );
  if (needsGuard)
    head.push(
      "function guard(ctx: { user: unknown }, roles?: string[]) {",
      '  if (!ctx.user) throw new SpeeqError("UNAUTHENTICATED");',
      "  if (roles) {",
      "    const have = (ctx.user as { roles?: unknown }).roles;",
      '    if (!Array.isArray(have) || !roles.some((r) => have.includes(r))) throw new SpeeqError("FORBIDDEN");',
      "  }",
      "}",
      "",
    );
  const body = tools.length
    ? `export const tools = [\n${items.join("\n")}\n];`
    : "export const tools: ToolDefinition<never, never>[] = [];";
  return `${head.join("\n")}\n${body}\n`;
}
/** Source of `.speeq/generated/routes.ts` (without the ownership header). */
export function renderRoutes(routes: readonly RouteSpec[]): string {
  const items = routes.map((r) =>
    [
      "  defineRoute({",
      `    id: ${q(r.id)},`,
      `    path: ${q(r.path)},`,
      `    title: ${q(r.title)},`,
      ...(r.description ? [`    description: ${q(r.description)},`] : []),
      ...(r.params ? [`    params: ${r.params},`] : []),
      "  }),",
    ].join("\n"),
  );
  const head = [NOTE];
  head.push(
    routes.length
      ? 'import { defineRoute, type RouteDefinition } from "speeq/server";'
      : 'import type { RouteDefinition } from "speeq/server";',
  );
  if (routes.some((r) => r.params)) head.push('import { z } from "zod";');
  const body = routes.length
    ? `export const routes: RouteDefinition[] = [\n${items.join("\n")}\n];`
    : "export const routes: RouteDefinition[] = [];";
  return `${head.join("\n")}\n\n${body}\n`;
}
/** Source of the App Router handler (without the ownership header). */
export function renderHandler(file: string, configFile: string): string {
  return [
    NOTE,
    'import { createNextHandler } from "speeq/server/next";',
    `import { speeq } from ${q(importPath(file, configFile))};`,
    "",
    'export const runtime = "nodejs";',
    "",
    "export const { GET, POST, OPTIONS } = createNextHandler(speeq);",
    "",
  ].join("\n");
}
/** Source of `speeq.config.ts`. Written once; the developer owns it afterwards. */
export function renderConfig(o: {
  provider: ProviderEntry;
  features: readonly FeatureEntry[];
  generatedDir: string;
  configFile: string;
}): string {
  const imports = new Map<string, Set<string>>([["speeq/server", new Set(["createSpeeq"])]]);
  imports.set("speeq/store-memory", new Set(["createMemoryStore"]));
  for (const i of o.provider.imports)
    imports.set(i.from, new Set([...(imports.get(i.from) ?? []), ...i.names]));
  const lines = [...imports].map(
    ([from, names]) => `import { ${[...names].sort().join(", ")} } from ${q(from)};`,
  );
  const gen = (name: string) => q(importPath(o.configFile, `${o.generatedDir}/${name}`));
  return [
    "// Created by `speeq init`. This file is yours: speeq never overwrites it.",
    ...lines,
    `import { routes } from ${gen("routes")};`,
    `import { tools } from ${gen("tools")};`,
    "",
    "export const speeq = createSpeeq({",
    "  secret: process.env.SPEEQ_SECRET,",
    '  agent: { name: "Assistant", instructions: "You help people use this website. Use the tools and routes you are given. Say so when you cannot do something." },',
    `  llm: ${o.provider.expression},`,
    "  // In-memory store: conversations are lost on restart. Use speeq/store-mongodb for production.",
    "  store: createMemoryStore(),",
    "  // Return the signed-in user from your own session, e.g. { id: session.user.id }.",
    "  // resolveUser: async (request) => null,",
    "  routes,",
    "  tools,",
    ...o.features.flatMap((f) => f.config),
    "});",
    "",
  ].join("\n");
}
/** The manual snippet for the root layout (a client wrapper, because the provider uses hooks). */
export function layoutSnippet(): string {
  return [
    "// components/speeq-provider.tsx",
    '"use client";',
    'import { SpeeqProvider } from "speeq/react";',
    "",
    "export function Speeq({ children }: { children: React.ReactNode }) {",
    '  return <SpeeqProvider endpoint="/api/speeq">{children}</SpeeqProvider>;',
    "}",
    "",
    "// app/layout.tsx: wrap {children} with <Speeq>...</Speeq>",
  ].join("\n");
}
