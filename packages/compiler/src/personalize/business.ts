import type { Evidence, Manifest } from "@speeq/core/manifest";
import type ts from "typescript";
import { cleanText } from "../jsdoc.js";
import { literalMetadata } from "../nextjs/metadata.js";

/** One fact about the business with where it came from. */
export interface BusinessFact {
  value: string;
  evidence: Evidence;
}

/**
 * What the code says about the business. Each fact is a suggestion with evidence for the developer
 * to confirm in `speeq setup`; a package name alone is never treated as a description.
 */
export interface BusinessFacts {
  name?: BusinessFact;
  description?: BusinessFact;
  url?: BusinessFact;
  /** Public page titles, at most ten, for terminology and offerings hints. */
  pages: { title: string; path: string }[];
  /** True when nothing reliable describes what the business does: ask the developer. */
  needsDescription: boolean;
}

const fact = (value: string, file: string, line: number, detector: string, note: string) => ({
  value,
  evidence: { file, line, detector, note },
});
function lineOf(text: string, needle: string): number {
  const i = text.split("\n").findIndex((l) => l.includes(needle));
  return i >= 0 ? i + 1 : 1;
}
/** `my-shop_app` → `My Shop App`; scoped names lose the scope. */
function titleCase(pkg: string): string {
  return pkg
    .replace(/^@[^/]+\//, "")
    .split(/[-_.\s]+/)
    .filter(Boolean)
    .map((w) => w[0]?.toUpperCase() + w.slice(1))
    .join(" ");
}

/** README: first `# Heading` and the first plain paragraph after it. */
function readme(text: string): {
  title?: string;
  titleLine?: number;
  para?: string;
  paraLine?: number;
} {
  const lines = text.split("\n");
  const h = lines.findIndex((l) => /^#\s+\S/.test(l));
  if (h < 0) return {};
  const title = cleanText(lines[h]?.replace(/^#\s+/, "") ?? "", 80);
  let p = h + 1;
  while (
    p < lines.length &&
    (!lines[p]?.trim() || /^(?:[#>!<[|`-]|\s*\*|\s*\d+\.)/.test(lines[p] ?? ""))
  )
    p++;
  const paraLines: string[] = [];
  for (let i = p; i < lines.length && lines[i]?.trim(); i++) paraLines.push(lines[i] ?? "");
  const para = cleanText(paraLines.join(" ").replace(/[*_`]/g, ""), 300);
  return { title, titleLine: h + 1, ...(para.length >= 20 ? { para, paraLine: p + 1 } : {}) };
}
const GENERIC = /^(?:create next app|next\.js|my app|untitled|app|website|home)$/i;

/**
 * Reads business facts from the root layout metadata, package.json and the README, in that order
 * of trust. Reads files only; never runs code.
 */
export function discoverBusiness(input: {
  layout?: { file: string; sf: ts.SourceFile };
  packageJson?: { file: string; text: string };
  readme?: { file: string; text: string };
  manifest: Manifest;
}): BusinessFacts {
  let name: BusinessFact | undefined;
  let description: BusinessFact | undefined;
  let url: BusinessFact | undefined;
  if (input.layout) {
    const m = literalMetadata(input.layout.sf);
    const text = input.layout.sf.getFullText();
    if (m.title && !GENERIC.test(m.title))
      name = fact(
        m.title,
        input.layout.file,
        lineOf(text, "title"),
        "layout-metadata",
        "metadata.title in the root layout",
      );
    if (m.description && !/generated by create next app/i.test(m.description))
      description = fact(
        m.description,
        input.layout.file,
        lineOf(text, "description"),
        "layout-metadata",
        "metadata.description in the root layout",
      );
  }
  if (input.packageJson) {
    const { file, text } = input.packageJson;
    try {
      const pkg = JSON.parse(text) as { name?: unknown; description?: unknown; homepage?: unknown };
      if (
        !description &&
        typeof pkg.description === "string" &&
        pkg.description.trim().length >= 10
      )
        description = fact(
          cleanText(pkg.description, 300),
          file,
          lineOf(text, '"description"'),
          "package-json",
          "package.json description",
        );
      if (typeof pkg.homepage === "string" && /^https?:\/\//.test(pkg.homepage))
        url = fact(
          pkg.homepage.slice(0, 200),
          file,
          lineOf(text, '"homepage"'),
          "package-json",
          "package.json homepage",
        );
      if (!name && typeof pkg.name === "string" && pkg.name.trim()) {
        const t = titleCase(pkg.name);
        if (t && !GENERIC.test(t))
          name = fact(
            t,
            file,
            lineOf(text, '"name"'),
            "package-name",
            "package.json name (only a hint)",
          );
      }
    } catch {
      // A malformed package.json gives no facts.
    }
  }
  if (input.readme) {
    const r = readme(input.readme.text);
    if (r.title && !GENERIC.test(r.title) && (!name || name.evidence.detector === "package-name"))
      name = fact(
        r.title,
        input.readme.file,
        r.titleLine ?? 1,
        "readme-heading",
        "first README heading",
      );
    if (!description && r.para)
      description = fact(
        r.para,
        input.readme.file,
        r.paraLine ?? 1,
        "readme-paragraph",
        "first README paragraph",
      );
  }
  const pages = input.manifest.capabilities
    .flatMap((c) =>
      c.kind === "route" && !c.pathParams.length && c.sensitivity === "none"
        ? [{ title: c.title, path: c.path }]
        : [],
    )
    .filter(
      (p) => p.path !== "/" && !/\/(?:login|sign-?in|sign-?up|register|admin)(?:\/|$)/.test(p.path),
    )
    .slice(0, 10);
  return {
    ...(name ? { name } : {}),
    ...(description ? { description } : {}),
    ...(url ? { url } : {}),
    pages,
    needsDescription: !description,
  };
}
